/** Isolated v2 development setup. Never publishes artifacts or reads deployment signers. */
import { execFileSync } from "node:child_process";
import { createHash, randomBytes } from "node:crypto";
import fs from "node:fs";
import path from "node:path";
import { V2_PROTOCOL } from "../../../shared/privacy/v2/notes";

const root = path.resolve(import.meta.dirname, "../../..");
const build = path.join(root, "circuits/v2/build");
const verifierDir = path.join(root, "contracts/src/v2/dev-verifiers");
const ptau = path.join(root, "circuits/ptau/powersOfTau28_hez_final_16.ptau");
const cli = path.join(root, "node_modules/snarkjs/build/cli.cjs");
const sha256 = (file: string) =>
  createHash("sha256").update(fs.readFileSync(file)).digest("hex");
function run(...args: string[]) {
  execFileSync(process.execPath, args, {
    cwd: root,
    stdio: "inherit",
    maxBuffer: 1 << 28,
  });
}
const snark = (...args: string[]) => run(cli, ...args);

function main() {
  if (process.argv.length > 2)
    throw new Error(
      "Usage: npm run zk:v2:build:dev (no deployment or publication flags)"
    );
  if (!fs.existsSync(ptau))
    throw new Error(
      "Development ptau absent. Obtain the frozen development transcript; do not rebuild v1."
    );
  fs.mkdirSync(build, { recursive: true });
  fs.mkdirSync(verifierDir, { recursive: true });
  // Invalidate any previous completion marker before writing new keys.
  const manifestPath = path.join(build, "manifest.json");
  fs.writeFileSync(
    manifestPath,
    JSON.stringify({
      protocol: V2_PROTOCOL,
      status: "building",
      productionReady: false,
    })
  );
  snark("powersoftau", "verify", ptau);
  const circuits: Record<string, unknown> = {};
  for (const [name, contract] of [
    ["withdraw", "WithdrawVerifierV2Dev"],
    ["commitment", "CommitmentVerifierV2Dev"],
  ]) {
    const source = path.join(root, `circuits/v2/${name}.circom`);
    run(
      path.join(root, "node_modules/circom2/cli.js"),
      source,
      "--r1cs",
      "--wasm",
      "--sym",
      "--O1",
      "-o",
      build,
      "-l",
      "node_modules"
    );
    const r1cs = path.join(build, `${name}.r1cs`);
    const initial = path.join(build, `${name}_0000.zkey`);
    const zkey = path.join(build, `${name}_final.zkey`);
    const vkey = path.join(build, `${name}_verification_key.json`);
    snark("groth16", "setup", r1cs, ptau, initial);
    // Development entropy must not be printed into the command log.
    snark(
      "zkey",
      "contribute",
      initial,
      zkey,
      "--name=hylsia-v2-DEVELOPMENT-ONLY",
      `-e=${randomBytes(32).toString("hex")}`
    );
    snark("zkey", "verify", r1cs, ptau, zkey);
    snark("zkey", "export", "verificationkey", zkey, vkey);
    const generated = path.join(build, `${name}_verifier.sol`);
    snark("zkey", "export", "solidityverifier", zkey, generated);
    const verifier = path.join(verifierDir, `${contract}.sol`);
    fs.writeFileSync(
      verifier,
      "// DEVELOPMENT ONLY. Generated by scripts/privacy/v2/build-dev.ts. Not a mainnet verifier.\n" +
        fs
          .readFileSync(generated, "utf8")
          .replace(/contract Groth16Verifier/g, `contract ${contract}`)
    );
    circuits[name] = {
      sourceSha256: sha256(source),
      r1csSha256: sha256(r1cs),
      zkeySha256: sha256(zkey),
      wasmSha256: sha256(path.join(build, `${name}_js/${name}.wasm`)),
      vkeySha256: sha256(vkey),
      verifierSha256: sha256(verifier),
    };
  }
  fs.writeFileSync(
    manifestPath,
    JSON.stringify(
      {
        protocol: V2_PROTOCOL,
        status: "development",
        productionReady: false,
        compilerOptimization: "O1",
        ptauSha256: sha256(ptau),
        merkleProofSha256: sha256(
          path.join(root, "circuits/lib/merkleProof.circom")
        ),
        circuits,
      },
      null,
      2
    ) + "\n"
  );
  const pins = circuits as Record<string, { vkeySha256: string }>;
  fs.writeFileSync(path.join(root, "shared/privacy/v2/devKeyPins.ts"),
    "/** Development-only v2 key pins, generated from the separately verified v2 setup. */\n"
    + `export const V2_DEV_KEY_PINS = Object.freeze({ withdraw: "${pins.withdraw.vkeySha256}", commitment: "${pins.commitment.vkeySha256}" });\n`);
  console.log(
    "V2 development setup complete. Regenerate v2 fixtures before running contract tests. Mainnet remains blocked."
  );
}

try {
  main();
} catch (error) {
  console.error(error);
  process.exitCode = 1;
}
